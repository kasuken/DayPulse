namespace DayPulse.Core.Domain;

/// <summary>
/// Visual theme preferences supported by the application.
/// </summary>
public enum ThemeMode
{
    /// <summary>
    /// Follow the operating system theme.
    /// </summary>
    System,

    /// <summary>
    /// Always use the light theme.
    /// </summary>
    Light,

    /// <summary>
    /// Always use the dark theme.
    /// </summary>
    Dark
}
